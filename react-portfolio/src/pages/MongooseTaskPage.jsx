// ─── Mongoose ObjectId simulator ─────────────────────────────────────────────
const genObjectId = () => {
  const hex = () => Math.floor(Math.random() * 16).toString(16);
  const seg = (n) => Array.from({ length: n }, hex).join('');
  return `${seg(8)}${seg(4)}${seg(4)}${seg(4)}${seg(12)}`;
};

