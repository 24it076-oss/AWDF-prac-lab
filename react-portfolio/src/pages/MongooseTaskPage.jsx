// ─── Mongoose Schema fields description for display ───────────────────────────
const SCHEMA_FIELDS = [
  { field: 'title',       type: 'String',  constraints: 'required, minlength: 3, maxlength: 100, trim: true', default: '—' },
  { field: 'description', type: 'String',  constraints: 'trim, maxlength: 500',                               default: '""' },
  { field: 'status',      type: 'String',  constraints: 'enum: [Pending, In Progress, Completed]',            default: '"Pending"' },
  { field: 'priority',    type: 'String',  constraints: 'enum: [Low, Medium, High]',                         default: '"Medium"' },
  { field: 'dueDate',     type: 'Date',    constraints: 'optional',                                           default: 'null' },
  { field: 'isCompleted', type: 'Boolean', constraints: 'pre-save hook: status === "Completed"',              default: 'false' },
  { field: 'tags',        type: '[String]',constraints: 'array of strings',                                   default: '[]' },
  { field: '_id',         type: 'ObjectId','constraints': 'auto-generated by MongoDB',                        default: 'auto' },
  { field: 'createdAt',   type: 'Date',    constraints: 'timestamps: true',                                   default: 'auto' },
  { field: 'updatedAt',   type: 'Date',    constraints: 'timestamps: true',                                   default: 'auto' },
];

/**
 * MongooseTaskPage (Route: /mongo-tasks)
 * Practical 5 — MongoDB Integration & Schema Design with Mongoose
 */
export default function MongooseTaskPage() {
  const [tasks, setTasks] = useState(INITIAL_TASKS);
  const [activeFilter, setActiveFilter] = useState('All');
  const [showSchema, setShowSchema] = useState(true);

  // Form state
  const [newTitle,    setNewTitle]    = useState('');
  const [newDesc,     setNewDesc]     = useState('');
  const [newPriority, setNewPriority] = useState('Medium');
  const [newDueDate,  setNewDueDate]  = useState('');
  const [newTags,     setNewTags]     = useState('');
  const [formError,   setFormError]   = useState('');

  // Terminal logs
  const [logs, setLogs] = useState([
    { id: 1, text: 'mongoose.connect("mongodb://127.0.0.1:27017/task_manager_db") → connected ✔', type: 'success' },
    { id: 2, text: '[Mongoose] Connection readyState: 1 (connected)', type: 'info' },
    { id: 3, text: 'Task.find({}) → 3 documents returned from collection "tasks"', type: 'success' },
  ]);

  const addLog = (text, type = 'success') => {
    const ts = new Date().toISOString();
    setLogs(prev => [{ id: Date.now(), text: `[${ts}] ${text}`, type }, ...prev.slice(0, 11)]);
  };

  // CREATE
  const handleCreate = (e) => {
    e.preventDefault();
    if (!newTitle.trim() || newTitle.trim().length < 3) {
      setFormError('Mongoose ValidationError: title must be at least 3 characters (required).');
      addLog('Task.create() → ValidationError: title fails minlength(3)', 'error');
      return;
    }
    const id = genObjectId();
    const now = new Date().toISOString();
    const tagArr = newTags.split(',').map(t => t.trim()).filter(Boolean);
    const task = {
      _id: id,
      title: newTitle.trim(),
      description: newDesc.trim() || '',
      status: 'Pending',
      priority: newPriority,
      dueDate: newDueDate || null,
      isCompleted: false,
      tags: tagArr,
      createdAt: now,
      updatedAt: now,
    };
    setTasks(prev => [task, ...prev]);
    setNewTitle(''); setNewDesc(''); setNewTags(''); setNewDueDate(''); setFormError('');
    addLog(`Task.create({ title: "${task.title}" }) → _id: ${id} inserted`, 'success');
  };

  // TOGGLE STATUS (UPDATE)
  const handleToggle = (id) => {
    setTasks(prev =>
      prev.map(t => {
        if (t._id === id) {
          const next =
            t.status === 'Pending' ? 'In Progress'
            : t.status === 'In Progress' ? 'Completed'
            : 'Pending';
          const completed = next === 'Completed';
          addLog(`Task.findByIdAndUpdate("${id}", { status: "${next}", isCompleted: ${completed} }, { runValidators: true }) → 200`, 'success');
          return { ...t, status: next, isCompleted: completed, updatedAt: new Date().toISOString() };
        }
        return t;
      })
    );
  };

  // DELETE
  const handleDelete = (id) => {
    setTasks(prev => prev.filter(t => t._id !== id));
    addLog(`Task.findByIdAndDelete("${id}") → document removed`, 'warn');
  };

  // Validation error demo
  const handleValidationTest = () => {
    addLog('Task.create({ title: "" }) → ValidationError: Path `title` is required.', 'error');
  };

  // CastError demo
  const handleCastErrorTest = () => {
    addLog('Task.findById("not-a-valid-id") → CastError: Cast to ObjectId failed for value "not-a-valid-id"', 'error');
  };

  const filtered = activeFilter === 'All' ? tasks : tasks.filter(t => t.status === activeFilter);

  return (
    <div className="page-task-manager">
      {/* ── Header ── */}
      <div className="section-header">
        <div>
          <h1 className="section-heading">MongoDB Integration with Mongoose</h1>
          <p className="page-subtitle">
            Practical 5 — Schema design, Mongoose CRUD, field validation, ObjectId, and timestamps.
          </p>
        </div>
        <span className="section-tag" style={{ background: 'var(--mongo-green, #4DB33D)', color: '#fff' }}>
          🍃 mongoose@8 + MongoDB
        </span>
      </div>

      {/* ── Connection Pipeline ── */}
      <div className="pipeline-flow-banner" style={{ background: '#0d2a1a', borderColor: '#2d6a4f' }}>
        <span className="flow-badge" style={{ background: '#4DB33D', color: '#fff' }}>Mongoose Pipeline</span>
        <span className="flow-step">dotenv.config()</span> →
        <span className="flow-step">connectDB()</span> →
        <span className="flow-step">mongoose.connect(MONGO_URI)</span> →
        <span className="flow-step">Schema + Model</span> →
        <span className="flow-step">CRUD Operations</span> →
        <span className="flow-step">ValidationError / CastError Handler</span>
      </div>

      {/* ── Schema Toggle ── */}
      <div style={{ marginBottom: '1rem' }}>
        <button
          className="btn btn-secondary btn-sm"
          onClick={() => setShowSchema(v => !v)}
          style={{ fontSize: '0.8rem' }}
        >
          {showSchema ? '▲ Hide' : '▼ Show'} Mongoose Schema Definition
        </button>
      </div>

      {/* ── Schema Table ── */}
      {showSchema && (
        <div className="schema-panel">
          <h3 className="schema-panel-title">
            <span style={{ color: '#4DB33D' }}>●</span> Task Schema — <code>models/Task.js</code>
          </h3>
          <div className="schema-table-wrap">
            <table className="schema-table">
              <thead>
                <tr>
                  <th>Field</th>
                  <th>Type</th>
                  <th>Constraints / Notes</th>
                  <th>Default</th>
                </tr>
              </thead>
              <tbody>
                {SCHEMA_FIELDS.map(row => (
                  <tr key={row.field}>
                    <td><code className="field-code">{row.field}</code></td>
                    <td><span className="type-badge">{row.type}</span></td>
                    <td style={{ fontSize: '0.78rem', color: 'var(--text-muted)' }}>{row.constraints}</td>
                    <td><code style={{ fontSize: '0.75rem' }}>{row.default}</code></td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </div>
      )}

      {/* ── Main Grid ── */}
      <div className="task-manager-grid">
        {/* Left: Create Form */}
        <div className="task-form-panel">
          <h2 className="panel-title">Task.create() — POST /api/tasks</h2>

          <form onSubmit={handleCreate} noValidate>
            <div className="form-group">
              <label className="form-label">Title <span className="required">*</span> <small>(min 3 chars)</small></label>
              <input
                type="text"
                value={newTitle}
                onChange={e => { setNewTitle(e.target.value); setFormError(''); }}
                placeholder="e.g. Setup MongoDB Atlas Cluster"
                className={`form-input ${formError ? 'input-error' : ''}`}
              />
              {formError && <span className="error-message" style={{ fontSize: '0.72rem' }}>{formError}</span>}
            </div>

            <div className="form-group">
              <label className="form-label">Description <small>(maxlength 500)</small></label>
              <textarea rows="2" value={newDesc} onChange={e => setNewDesc(e.target.value)}
                placeholder="Technical notes..." className="form-input form-textarea" />
            </div>

            <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: '0.6rem' }}>
              <div className="form-group">
                <label className="form-label">Priority</label>
                <select value={newPriority} onChange={e => setNewPriority(e.target.value)} className="form-input form-select">
                  <option>Low</option><option>Medium</option><option>High</option>
                </select>
              </div>
              <div className="form-group">
                <label className="form-label">Due Date</label>
                <input type="date" value={newDueDate} onChange={e => setNewDueDate(e.target.value)} className="form-input" />
              </div>
            </div>

            <div className="form-group">
              <label className="form-label">Tags <small>(comma-separated)</small></label>
              <input type="text" value={newTags} onChange={e => setNewTags(e.target.value)}
                placeholder="e.g. mongoose, api, lab" className="form-input" />
            </div>

            <button type="submit" className="btn btn-primary" style={{ width: '100%' }}>
              ➕ Task.create() — Insert Document
            </button>
          </form>

          {/* Diagnostics */}
          <div style={{ marginTop: '1.25rem', paddingTop: '1rem', borderTop: '1px solid var(--border-color)' }}>
            <span style={{ fontSize: '0.72rem', color: 'var(--text-muted)', display: 'block', marginBottom: '0.4rem' }}>
              Mongoose Error Diagnostics:
            </span>
            <button onClick={handleValidationTest} className="btn btn-secondary btn-sm"
              style={{ width: '100%', marginBottom: '0.4rem', color: 'var(--error-color)' }}>
              ⚠️ Simulate ValidationError (empty title)
            </button>
            <button onClick={handleCastErrorTest} className="btn btn-secondary btn-sm"
              style={{ width: '100%', color: '#f59e0b' }}>
              🔑 Simulate CastError (invalid ObjectId)
            </button>
          </div>
        </div>

        {/* Right: Task Documents */}
        <div className="tasks-display-panel">
          <div className="tasks-panel-top">
            <h2 className="panel-title">Task.find() — {filtered.length} MongoDB Documents</h2>
            <div className="filter-pill-group">
              {['All', 'Pending', 'In Progress', 'Completed'].map(st => (
                <button key={st} onClick={() => setActiveFilter(st)}
                  className={`filter-btn ${activeFilter === st ? 'active' : ''}`}
                  style={{ padding: '0.2rem 0.55rem', fontSize: '0.75rem' }}>
                  {st}
                </button>
              ))}
            </div>
          </div>

          <div className="task-cards-list">
            {filtered.map(task => (
              <div key={task._id} className="task-card-item">
                <div className="task-header-line">
                  <div className="task-title-group">
                    <span className="task-id-badge mongo-id" title={`ObjectId("${task._id}")`}>
                      🍃 {task._id.slice(0, 8)}…
                    </span>
                    <strong className="task-item-title">{task.title}</strong>
                  </div>
                  <div className="task-badges-row">
                    <span className={`priority-badge priority-${task.priority.toLowerCase()}`}>{task.priority}</span>
                    <span className={`status-badge-pill status-${task.status.toLowerCase().replace(' ', '-')}`}>{task.status}</span>
                    {task.isCompleted && <span className="completed-badge">✔ isCompleted</span>}
                  </div>
                </div>

                {task.description && <p className="task-item-desc">{task.description}</p>}

                {/* Tags */}
                {task.tags && task.tags.length > 0 && (
                  <div className="tags-row">
                    {task.tags.map(tag => (
                      <span key={tag} className="tag-pill">#{tag}</span>
                    ))}
                  </div>
                )}

                {/* Due Date & Timestamps */}
                <div className="task-meta-row">
                  {task.dueDate && (
                    <span className="meta-item">📅 Due: {task.dueDate.slice ? task.dueDate.slice(0, 10) : task.dueDate}</span>
                  )}
                  <span className="meta-item" style={{ color: 'var(--text-muted)', fontSize: '0.68rem' }}>
                    updatedAt: {new Date(task.updatedAt).toLocaleString()}
                  </span>
                </div>

                <div className="task-card-actions">
                  <button onClick={() => handleToggle(task._id)} className="btn btn-secondary btn-sm"
                    title="findByIdAndUpdate with runValidators">
                    ↻ Update Status
                  </button>
                  <button onClick={() => handleDelete(task._id)} className="btn btn-secondary btn-sm delete-btn"
                    title="findByIdAndDelete">
                    🗑️ Delete
                  </button>
                </div>
              </div>
            ))}
            {filtered.length === 0 && (
              <div style={{ textAlign: 'center', padding: '2rem', color: 'var(--text-muted)' }}>
                No documents match the current filter.
              </div>
            )}
          </div>
        </div>
      </div>

      {/* ── Mongoose Terminal ── */}
      <div className="middleware-logger-terminal" style={{ borderColor: '#2d6a4f' }}>
        <div className="terminal-header" style={{ background: '#0d2a1a', borderBottom: '1px solid #2d6a4f' }}>
          <span className="terminal-dot red" />
          <span className="terminal-dot yellow" />
          <span className="terminal-dot green" />
          <span className="terminal-title" style={{ color: '#4DB33D' }}>
            🍃 Mongoose Query Log — mongodb://127.0.0.1:27017/task_manager_db
          </span>
        </div>
        <div className="terminal-body" style={{ background: '#071510' }}>
          {logs.map(log => (
            <div key={log.id} className={`terminal-log-line log-${log.type}`}>
              {log.text}
            </div>
          ))}
        </div>
      </div>
    </div>
  );
}
